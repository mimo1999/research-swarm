"""Render the pipeline-v2 ablation table from saved ``compare_runs.py --json`` files.

    python benchmarks/ablation_table.py --update-readme

Each step's comparison is against the previously accepted run, so a row's mean is the
*cumulative* configuration and the ``vs previous`` cell lists the paired differences whose 95% CI
excluded zero. Configurations run on the fixed 90-task subset (``make_ablation_subset.py``).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bench_common import RESULTS_ROOT, ROOT, md_table, update_block  # noqa: E402

# (label, compare file stem, description); the first entry's *baseline* is the "v1" row.
STEPS: list[tuple[str, str, str]] = [
    ("+ question to writer/extractor", "abl-step1", "Step 1"),
    ("+ grounded evidence windows", "abl-step2", "Step 2"),
    ("+ single verifier", "abl-step4b", "Step 4"),
    ("+ multi-fact packed extraction", "abl-step3", "Step 3"),
    ("+ attributed writer", "abl-step5", "Step 5"),
    ("+ gap fill, 2 facts/sub-question (closed corpus)", "abl-step7", "Step 7"),
]
COLUMNS = [
    ("answer_score", "Answer"), ("finding_recall", "Finding recall"),
    ("false_refute_rate", "False-refute"), ("faithfulness", "Faithfulness"),
    ("citation_recall", "Cite recall"), ("citation_completeness", "Cite complete."),
    ("critical_error", "Critical err."), ("seconds", "Time (s)"), ("llm_calls", "LLM calls"),
]


def _row_by_metric(compare: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {r["metric"]: r for r in compare["rows"]}


def _fmt(value: Any, metric: str) -> str:
    if value is None:
        return "-"
    return f"{value:.1f}" if metric in ("seconds", "llm_calls") else f"{value:.2f}"


def render(root: Path = RESULTS_ROOT) -> str:
    loaded = []
    for label, stem, _ in STEPS:
        path = root / f"{stem}-compare.json"
        if path.exists():
            loaded.append((label, json.loads(path.read_text(encoding="utf-8"))))
    if not loaded:
        return "(no ablation comparisons found)"

    rows: list[list[Any]] = []
    first = _row_by_metric(loaded[0][1])
    rows.append(["v1 pipeline (re-run baseline)"]
                + [_fmt(first.get(m, {}).get("baseline"), m) for m, _ in COLUMNS] + ["-"])
    for label, comp in loaded:
        by = _row_by_metric(comp)
        sig = [f"{r['metric']} {'+' if (r['diff'][0] > 0) else ''}{r['diff'][0]:.2f} {r['verdict']}"
               for r in comp["rows"] if r["verdict"]]
        rows.append([label] + [_fmt(by.get(m, {}).get("candidate"), m) for m, _ in COLUMNS]
                    + ["; ".join(sig) or "no significant change"])
    header = ["Configuration (cumulative)"] + [c for _, c in COLUMNS] + ["Significant vs previous"]
    table = md_table(header, rows)
    return (
        "### Pipeline v2 ablation (fixed 90-task closed-corpus subset)\n\n"
        "Means over the same 90 tasks (30 each of ALCE, HotpotQA, SciFact) generated by "
        "`nemotron-3-nano:30b-cloud`; claim-level columns judged by `gemma4:31b-cloud` (not yet "
        "validated against hand labels). Each row adds one change to the previous row; the last "
        "column lists paired-bootstrap differences (candidate minus previous row) whose 95% CI "
        "excludes zero. Run-to-run noise is large (a re-run of the unchanged pipeline on another "
        "day produced 4x fewer findings), so only paired, same-day comparisons are meaningful.\n\n"
        + table
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update-readme", action="store_true")
    args = ap.parse_args()
    text = render()
    print(text)
    if args.update_readme:
        update_block(ROOT / "benchmarks" / "README.md", "ABLATION", text)
        print("README ablation block updated")


if __name__ == "__main__":
    main()
